// Writes config.yaml and src/markets.ts from contracts/deployments/<chainId>.json.
//   node gen-config.mjs 31337 [startBlock]   local anvil (RPC http://127.0.0.1:8545)
//   node gen-config.mjs 10143 <startBlock>   Monad testnet (HyperSync)
import fs from "node:fs";
import path from "node:path";
const [chainId = "31337", startBlock = "0"] = process.argv.slice(2);
const here = path.dirname(new URL(import.meta.url).pathname);
const dep = JSON.parse(fs.readFileSync(path.resolve(here, `../contracts/deployments/${chainId}.json`), "utf8"));
const cats = ["geopolitics", "tech_companies", "tech_personalities"].filter((k) => dep[k]);
const list = (xs) => xs.map((a) => `\n          - "${a}"`).join("");
// local anvil: its RPC. Monad testnet: HyperSync when ENVIO_API_TOKEN is set, otherwise the public RPC.
const rpc = chainId === "31337" ? "\n    rpc: http://127.0.0.1:8545"
  : process.env.ENVIO_API_TOKEN ? "" : `\n    rpc:\n      - url: ${process.env.MONAD_RPC ?? "https://testnet-rpc.monad.xyz"}\n        for: sync`;
fs.writeFileSync(path.join(here, "config.yaml"), `# yaml-language-server: $schema=./node_modules/envio/evm.schema.json
# Generated by gen-config.mjs from contracts/deployments/${chainId}.json. Do not edit by hand.
name: zeitgeist
description: Zeitgeist attention markets on Monad
contracts:
  - name: CategoryMarket
    events:
      - event: "Listed(uint256 indexed index, address token, string name, uint256 reserve, uint256 supply)"
        field_selection: { transaction_fields: [hash] }
      - event: "Bought(uint256 indexed index, address indexed buyer, address indexed to, uint256 assetIn, uint256 fee, uint256 sharesOut)"
        field_selection: { transaction_fields: [hash] }
      - event: "Sold(uint256 indexed index, address indexed seller, address indexed to, uint256 sharesIn, uint256 fee, uint256 assetOut)"
        field_selection: { transaction_fields: [hash] }
      - event: "Funded(uint256 indexed epoch, bytes32 inputsHash, int256[] deltas)"
        field_selection: { transaction_fields: [hash] }
      - event: "FeesCollected(uint256 toVoters, uint256 toTreasury)"
  - name: AttentionOracle
    events:
      - event: "TargetsPosted(bytes32 indexed category, uint64 asOf, bytes32 inputsHash, uint256[] targets)"
        field_selection: { transaction_fields: [hash] }
  - name: CategoryVoter
    events:
      - event: "Voted(uint256 indexed epoch, address indexed user, bytes32[] cats, uint256[] amounts)"
  - name: VotingEscrow
    events:
      - event: "Locked(address indexed user, uint256 amount, uint256 end)"
  - name: EntityGauge
    events:
      - event: "Staked(uint256 indexed i, address indexed user, uint256 amount)"
      - event: "Withdrawn(uint256 indexed i, address indexed user, uint256 amount)"
      - event: "RewardPaid(uint256 indexed i, address indexed user, uint256 amount)"
  - name: SealedCalls
    events:
      - event: "Sealed(address indexed caller, bytes16 indexed callId, uint64 horizonEnd, bytes ciphertext)"
      - event: "Revealed(address indexed caller, bytes16 indexed callId, bytes32 key)"
chains:
  - id: ${chainId}
    start_block: ${startBlock}${rpc}
    contracts:
      - name: CategoryMarket
        address:${list(cats.map((c) => dep[c]))}
      - name: AttentionOracle
        address: "${dep.oracle}"
      - name: CategoryVoter
        address: "${dep.voter}"
      - name: VotingEscrow
        address: "${dep.ve}"
      - name: EntityGauge
        address:${list(cats.map((c) => dep[`${c}_gauge`]))}
      - name: SealedCalls
        address: "${dep.calls}"
`);
const map = Object.fromEntries(cats.map((c) => [dep[c].toLowerCase(), c]));
const gauges = Object.fromEntries(cats.map((c) => [dep[`${c}_gauge`].toLowerCase(), c]));
fs.writeFileSync(path.join(here, "src/markets.ts"), `// Generated by gen-config.mjs. Market and gauge address -> category key.
export const MARKET_CATEGORY: Record<string, string> = ${JSON.stringify(map, null, 2)};
export const GAUGE_CATEGORY: Record<string, string> = ${JSON.stringify(gauges, null, 2)};
`);
console.log(`config.yaml for chain ${chainId}: ${cats.length} markets`);
